// YoniTube background.js v10
'use strict';
const SRV = 'http://127.0.0.1:5000';

const SK  = 'yn_s_v6';
const SK_OLD = 'yn_s_v5';

let _lastCookieExportTs = 0;
let _lastCookieExportHash = '';
const COOKIE_THROTTLE_MS = 60000;
const COOKIE_DOMAINS = ['.youtube.com','youtube.com','.music.youtube.com','music.youtube.com','.google.com','google.com','.accounts.google.com','accounts.google.com'];

function _hashString(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = ((h << 5) - h) + str.charCodeAt(i);
    h |= 0;
  }
  return String(h);
}

function _loadSettings(cb) {
  chrome.storage.local.get([SK, SK_OLD], r => {
    cb(Object.assign({}, r[SK_OLD] || {}, r[SK] || {}));
  });
}

function _isYoutubeRelevantCookie(c) {
  const domain = (c.domain || '').toLowerCase().replace(/^\./, '');
  if (domain === 'youtube.com' || domain.endsWith('.youtube.com')) return true;
  if (domain === 'music.youtube.com') return true;
  // Root Google auth cookies only — exclude chat/mail/drive/docs subdomains
  if (domain === 'google.com') return true;
  if (domain === 'accounts.google.com') return true;
  return false;
}

function _cookiesToNetscape(cookies) {
  let txt = '# Netscape HTTP Cookie File\n# Generated by YoniTube\n\n';
  (cookies || []).forEach(c => {
    if (!_isYoutubeRelevantCookie(c)) return;
    const val = c.value == null ? '' : String(c.value);
    if (val.includes('\t') || val.includes('\n') || val.includes('\r')) return;
    const httpOnly = c.httpOnly ? '#HttpOnly_' : '';
    const domain = c.domain.startsWith('.') ? c.domain : (c.hostOnly ? c.domain : '.' + c.domain);
    const flag = (c.domain.startsWith('.') || !c.hostOnly) ? 'TRUE' : 'FALSE';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const exp = c.expirationDate ? Math.round(c.expirationDate) : 0;
    txt += `${httpOnly}${domain}\t${flag}\t${c.path || '/'}\t${secure}\t${exp}\t${c.name}\t${val}\n`;
  });
  return txt;
}

async function _exportYoutubeCookies(force) {
  try {
    const now = Date.now();
    if (!force && now - _lastCookieExportTs < COOKIE_THROTTLE_MS) return;
    // Collect cookies from all relevant domains (matching popup COOKIE_DOMAINS)
    const raw = [];
    for (const d of COOKIE_DOMAINS) {
      try {
        const arr = await chrome.cookies.getAll({ domain: d });
        for (const c of arr || []) {
          if (c?.name) raw.push(c);
        }
      } catch {}
    }
    // Deduplicate by (domain, path, name)
    const seen = new Set();
    const cookies = [];
    for (const c of raw) {
      if (!_isYoutubeRelevantCookie(c)) continue;
      const key = `${c.domain}\t${c.path}\t${c.name}`;
      if (seen.has(key)) continue;
      seen.add(key);
      cookies.push(c);
    }
    if (!cookies.length) return;
    const txt = _cookiesToNetscape(cookies);
    const hash = _hashString(txt);
    if (!force && hash === _lastCookieExportHash) {
      _lastCookieExportTs = now;
      return;
    }
    _lastCookieExportHash = hash;
    _lastCookieExportTs = now;
    await fetch(SRV + '/update_cookies', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ cookies_txt: txt }),
    });
  } catch {}
}

function _sendToServer(body) {
  _exportYoutubeCookies(true).finally(() => {
    fetch(SRV + '/download', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    }).then(r => r.json()).then(d => {
      _bgSaveQueuedItem(d, body);
    }).catch(() => {});
  });
}

